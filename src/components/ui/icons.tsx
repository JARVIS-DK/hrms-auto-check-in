/**
 * Shared icons — one stroke language for the whole app.
 * 24×24 viewBox, round caps, stroke 2 (2.25 for denser badges).
 */

interface IconProps {
  size?: number;
  className?: string;
  /** Defaults to the surrounding text colour. */
  stroke?: string;
  strokeWidth?: number;
}

function base({ size = 16, className, stroke = "currentColor", strokeWidth = 2 }: IconProps) {
  return {
    "aria-hidden": true as const,
    width: size,
    height: size,
    viewBox: "0 0 24 24",
    fill: "none",
    stroke,
    strokeWidth,
    strokeLinecap: "round" as const,
    strokeLinejoin: "round" as const,
    className,
  };
}

